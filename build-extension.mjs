const classic = source.replace('export class Detector', 'class Detector').replace('export function covered', 'function covered');
await writeFile(new URL('./extension/detector-content.js', import.meta.url), `// Generated by build-extension.mjs; edit detector.mjs instead.\n(() => {\n${classic}\nglobalThis.VisionGuardDetector = { Detector, covered };\n})();\n`);
